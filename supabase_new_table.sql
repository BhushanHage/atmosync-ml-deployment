-- Creates a NEW table only. Does not alter existing tables or records.
create table if not exists public.weather_forecasts (
  id bigint generated by default as identity primary key,
  station text not null,
  station_id text not null,
  history_start date not null,
  history_end date not null,
  forecast_date date not null,
  forecast_horizon_day smallint not null check (forecast_horizon_day between 1 and 7),
  model text not null default 'LightGBM',
  model_version text not null default 'lightgbm-v1',
  predicted_max_temp_c double precision,
  predicted_min_temp_c double precision,
  predicted_mean_temp_c double precision,
  predicted_precip_mm double precision,
  forecast_generated_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  constraint weather_forecasts_station_forecast_date_key unique (station, forecast_date)
);
create index if not exists weather_forecasts_date_idx on public.weather_forecasts (forecast_date);
create index if not exists weather_forecasts_station_date_idx on public.weather_forecasts (station, forecast_date);
-- Enable RLS; API uses service-role credentials server-side only.
alter table public.weather_forecasts enable row level security;
